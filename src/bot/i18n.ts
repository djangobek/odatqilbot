const SORTED_RU = [...RU].sort((a, b) => b[0].length - a[0].length);

export function translateBotText(value: string, language: string): string {
  if (language !== 'ru') return value;
  let result = value;
  // Longer phrases first to avoid translating a word before its full sentence.
  for (const [uz, ru] of SORTED_RU) {
    result = result.split(uz).join(ru);
  }
  return result;
}

export function translateKeyboard<T>(markup: T, language: string): T {
  if (language !== 'ru' || !markup || typeof markup !== 'object') return markup;
  const walk = (value: unknown): unknown => {
    if (Array.isArray(value)) return value.map(walk);
    if (!value || typeof value !== 'object') return value;
    const out: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value as Record<string, unknown>)) {
      out[key] = key === 'text' && typeof item === 'string' ? translateBotText(item, language) : walk(item);
    }
    return out;
  };
  return walk(markup) as T;
}
